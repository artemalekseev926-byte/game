    enterGame(session) {
      this.session = session;
      this.lobby = null;
      this.show("game");
      this.renderer.setMap(session.map);
      this.renderer.selected = -1;
      this.renderer.targetMode = null;
      this.renderer.particles = [];
      this.renderer.fit();
      this.hud = new Hud(this, session, this.renderer);
      const home = session.s.provs.findIndex((P) => P.o === session.localPid);
      if (home >= 0) {
        this.renderer.focus(home, Math.max(this.renderer.cam.z * 2, 8));
        this.renderer.selected = home;
      }
      this.autosaveT = 60;
      let last2 = performance.now();
      const loop = (now) => {
        if (this.session !== session) return;
        const dt = Math.min(0.1, (now - last2) / 1e3);
        last2 = now;
        session.update(dt);
        this.renderer.draw(session, dt);
        this.hud.update(dt);
        if (session.mode === "offline" && session.s.winner === null) {
          this.autosaveT -= dt * (session.speed ? 1 : 0);
          if (this.autosaveT <= 0) {
            this.autosaveT = 60;
            this.saveTo("auto");
          }
        }
        requestAnimationFrame(loop);
      };
      requestAnimationFrame(loop);
    }
